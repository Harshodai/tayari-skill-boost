import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import { access } from 'node:fs/promises';
const root = new URL('../', import.meta.url);
const read = (file) => readFile(new URL(file, root), 'utf8');
const exists = async (file) => { await access(new URL(file, root)); };
const manifest = JSON.parse(await read('extension/manifest.json'));
assert.equal(manifest.manifest_version, 3);
assert.equal(manifest.version, '3.2.0');
for (const permission of ['sidePanel', 'contextMenus', 'identity', 'nativeMessaging', 'notifications']) assert.ok(manifest.permissions.includes(permission), `missing ${permission}`);
assert.equal(manifest.action.default_popup, undefined);
assert.equal(manifest.content_security_policy?.extension_pages, "script-src 'self'; object-src 'self'");
const captureMatches = manifest.content_scripts?.find((entry) => entry.js?.includes('omnisave_capture.js'))?.matches || [];
assert.ok(captureMatches.includes('https://medium.com/me/list*'), 'missing Medium Lists capture match');
assert.ok(captureMatches.includes('https://substack.com/saved*'), 'missing Substack Saved capture match');
assert.ok(manifest.externally_connectable?.matches?.includes('http://127.0.0.1:8083/*'), 'missing local 127.0.0.1 frontend origin');
assert.ok(manifest.host_permissions?.includes('http://127.0.0.1:8083/*'), 'missing local bridge host permission');
for (const file of ['extension/background.js', 'extension/content.js', 'extension/app_bridge.js', 'extension/sidepanel.html', 'extension/sidepanel.js', 'extension/auth/oauth.js', 'extension/auth/session.js', 'extension/nativeBridge.js']) await exists(file);
assert.ok(manifest.content_scripts?.some((entry) => entry.js?.includes('app_bridge.js') && entry.matches?.includes('http://127.0.0.1:8083/*')), 'missing trusted local app bridge match');
const options = await read('extension/options.html');
const optionsScript = await read('extension/options.js');
const background = await read('extension/background.js');
const content = await read('extension/content.js');
const panel = await read('extension/sidepanel.html');
const panelScript = await read('extension/sidepanel.js');
const nativeBridge = await read('extension/nativeBridge.js');
const oauth = await read('extension/auth/oauth.js');
const appBridge = await read('extension/app_bridge.js');
assert.match(appBridge, /jobtayari-extension-page-bridge-v1/);
assert.match(appBridge, /event\.origin !== window\.location\.origin/);
assert.match(appBridge, /omnisave_sync_now/);
const popup = await read('extension/popup.html');
const popupScript = await read('extension/popup.js');
assert.match(background, /set_token[\s\S]{0,160}Token push is disabled/);
assert.match(background, /TayariMessagePolicy\?\.isAuthorized/);
