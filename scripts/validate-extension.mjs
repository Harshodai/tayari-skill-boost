import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import { access } from 'node:fs/promises';
const root = new URL('../', import.meta.url);
const read = (file) => readFile(new URL(file, root), 'utf8');
const exists = async (file) => { await access(new URL(file, root)); };
const manifest = JSON.parse(await read('extension/manifest.json'));
assert.equal(manifest.manifest_version, 3);
assert.equal(manifest.version, '3.2.0');
for (const permission of ['sidePanel', 'contextMenus', 'identity', 'nativeMessaging', 'notifications']) assert.ok(manifest.permissions.includes(permission), `missing ${permission}`);
assert.equal(manifest.action.default_popup, undefined);
for (const file of ['extension/background.js', 'extension/content.js', 'extension/sidepanel.html', 'extension/sidepanel.js', 'extension/auth/oauth.js', 'extension/auth/session.js', 'extension/nativeBridge.js']) await exists(file);
const options = await read('extension/options.html');
const optionsScript = await read('extension/options.js');
const background = await read('extension/background.js');
const content = await read('extension/content.js');
const panel = await read('extension/sidepanel.html');
const panelScript = await read('extension/sidepanel.js');
const popup = await read('extension/popup.html');
const popupScript = await read('extension/popup.js');
assert.match(background, /set_token[\s\S]{0,160}Token push is disabled/);
assert.match(background, /TayariMessagePolicy\?\.isAuthorized/);
for (const marker of ['get_page_context', 'research_tabs', 'create_agent_task', 'answer_approved_page', 'approve_agent_plan', 'stop_agent_task', 'save_research_note', 'clear_research_notes', 'isResearchOriginAllowed']) assert.match(background, new RegExp(marker));
assert.match(content, /contentTrust:\s*['"]untrusted['"]/);
for (const id of ['agent-prompt', 'agent-mode', 'include-tabs', 'plan-task', 'approve-plan', 'takeover-task', 'stop-task', 'capture-page', 'save-selection', 'clear-evidence', 'answer-card', 'answer-text', 'open-desktop-task']) assert.match(panel, new RegExp(`id=["']${id}["']`));
assert.match(options, /id=["']apiUrl["']/);
assert.match(options, /id=["']appUrl["']/);
assert.match(optionsScript, /STORAGE_KEY\s*=\s*["']tayari_config["']/);
assert.match(optionsScript, /apiUrl/);
assert.match(optionsScript, /appUrl/);
assert.doesNotMatch(options, /backendUrl|apiKey/);
assert.doesNotMatch(optionsScript, /backendUrl|apiKey/);
assert.match(panel, /id=["']create-account["']/);
assert.match(panelScript, /open_tayari[\s\S]{0,180}auth\?mode=signup/);
assert.match(popup, /id=["']btn-create-account["']/);
assert.match(popupScript, /open_tayari[\s\S]{0,180}auth\?next=/);
assert.match(popupScript, /auth\?mode=signup/);
assert.doesNotMatch(popupScript, /path:\s*["']\/login["']/);
console.log('extension validation passed');
